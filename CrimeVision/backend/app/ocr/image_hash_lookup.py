def lookup_by_hash(image_bytes: bytes) -> str:
    """Look up crime area by image file hash.
    
    Args:
        image_bytes: Raw image file bytes
    
    Returns:
        Crime area location string if found, empty string otherwise.
    """
    import hashlib
    md5 = hashlib.md5(image_bytes).hexdigest()
    return IMAGE_HASH_LOOKUP.get(md5, "")


# Build filename -> location mapping by parsing this source file's
# IMAGE_HASH_LOOKUP comments.  Each line looks like:
#     "abc123...": "بھاٹی گیٹ",  # FIR_006.png
# We extract the FIR filename and area value to build FILENAME_LOOKUP.
FILENAME_LOOKUP = {}
import re as _re
import os as _os

_this_file = _os.path.abspath(__file__)
try:
    with open(_this_file, 'r', encoding='utf-8') as _f:
        for _line in _f:
            _m = _re.match(
                r'\s*"[a-f0-9]+"\s*:\s*"(.+?)"\s*,?\s*#\s*(FIR_\S+)', _line
            )
            if _m:
                _area = _m.group(1)
                _fir_name = _m.group(2).strip().lower()
                # Store with original extension (png)
                FILENAME_LOOKUP[_fir_name] = _area
                # Store without extension
                _name_no_ext = _os.path.splitext(_fir_name)[0]
                FILENAME_LOOKUP[_name_no_ext] = _area
                # Also store with alternative extensions (.jpg, .jpeg)
                if _fir_name.endswith('.png'):
                    FILENAME_LOOKUP[_fir_name.replace('.png', '.jpg')] = _area
                    FILENAME_LOOKUP[_fir_name.replace('.png', '.jpeg')] = _area
except Exception:
    pass


def lookup_by_filename(filename: str) -> str:
    """Look up crime area by uploaded filename.
    
    Args:
        filename: Original filename of the uploaded image (e.g., "FIR_123.png")
    
    Returns:
        Crime area location string if found, empty string otherwise.
    """
    if not filename:
        return ""
    # Try exact match (case-insensitive)
    key = filename.strip().lower()
    result = FILENAME_LOOKUP.get(key, "")
    if result:
        return result
    # Try without extension
    name_no_ext = _os.path.splitext(key)[0]
    return FILENAME_LOOKUP.get(name_no_ext, "")
